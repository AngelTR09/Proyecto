"""# 5. Selección del modelo
**Enfoque:** aprendizaje supervisado, regresión (se predice la RUL en ciclos).

| Modelo | Rol |
|---|---|
| Ridge | Modelo base (baseline lineal) |
| Random Forest | Ensamble (bagging), robusto al ruido |
| Boosting (XGBoost, o HistGradientBoosting si XGBoost no está instalado) | Ensamble (boosting), muy fuerte en datos tabulares |
| SVR (kernel RBF) | Relaciones no lineales suaves |
| MLP | Red neuronal densa |

Todos se encapsulan en un `Pipeline` con `StandardScaler`, de modo que el escalado se ajusta solo con los datos de entrenamiento de cada pliegue.
"""

def build_models():
    if HAS_XGB:
        boost = XGBRegressor(n_estimators=300, learning_rate=0.05, max_depth=5, subsample=0.9,
                             colsample_bytree=0.9, random_state=SEED, n_jobs=-1, verbosity=0)
        boost_space = {"m__n_estimators": [200, 400, 600], "m__learning_rate": [0.03, 0.05, 0.1],
                       "m__max_depth": [3, 5, 7], "m__subsample": [0.7, 0.9, 1.0],
                       "m__colsample_bytree": [0.7, 0.9, 1.0]}
        boost_name = "XGBoost"
    else:
        boost = HistGradientBoostingRegressor(max_iter=300, learning_rate=0.05, max_depth=5, random_state=SEED)
        boost_space = {"m__max_iter": [200, 400, 600], "m__learning_rate": [0.03, 0.05, 0.1],
                       "m__max_depth": [3, 5, 7], "m__min_samples_leaf": [20, 50, 100]}
        boost_name = "HistGradientBoosting"

    def pipe(est):
        return Pipeline([("sc", StandardScaler()), ("m", est)])

    models = {
        "Ridge": pipe(Ridge(alpha=1.0, random_state=SEED)),
        "RandomForest": pipe(RandomForestRegressor(n_estimators=150, min_samples_leaf=5, max_features=0.5,
                                                         n_jobs=-1, random_state=SEED)),
        boost_name: pipe(boost),
        "SVR": pipe(SVR(C=10, gamma="scale", epsilon=1.0)),
        "MLP": pipe(MLPRegressor(hidden_layer_sizes=(64, 32), alpha=1e-3, early_stopping=True,
                                 max_iter=300, random_state=SEED)),
    }
    spaces = {
        "Ridge": {"m__alpha": [0.01, 0.1, 1, 10, 100]},
        "RandomForest": {"m__n_estimators": [100, 200, 300], "m__max_depth": [8, 12, 16],
                         "m__min_samples_leaf": [3, 5, 10], "m__max_features": [0.3, 0.5]},
        boost_name: boost_space,
        "SVR": {"m__C": [1, 10, 100], "m__gamma": ["scale", 0.01, 0.1], "m__epsilon": [0.1, 1]},
        "MLP": {"m__hidden_layer_sizes": [(64,), (64, 32), (128, 64)], "m__alpha": [1e-4, 1e-3],
                "m__learning_rate_init": [1e-3, 1e-2]},
    }
    return models, spaces

models, spaces = build_models()
