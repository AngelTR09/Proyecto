"""## 4.3. Ingeniería de características (solo información pasada)
Por motor y por sensor se generan: media móvil (5 y 10 ciclos), desviación estándar móvil (10), diferencia con el ciclo anterior y pendiente local (regresión lineal sobre los últimos 10 ciclos).
Las ventanas son **causales** (solo ciclos pasados y el actual). Con ventana incompleta se usa `min_periods`.
"""

def _slope(a):
    n = len(a)
    t = np.arange(n) - (n - 1) / 2.0
    return (t * a).sum() / (t * t).sum()

def add_window_features(df, sensors, windows=(5, 10)):
    df = df.sort_values(["unit", "cycle"]).reset_index(drop=True)
    g = df.groupby("unit")
    new = {}
    for s in sensors:
        for w in windows:
            new[f"{s}_mean{w}"] = g[s].transform(lambda x: x.rolling(w, min_periods=1).mean())
        new[f"{s}_std10"] = g[s].transform(lambda x: x.rolling(10, min_periods=2).std()).fillna(0.0)
        new[f"{s}_diff"] = g[s].diff().fillna(0.0)
        new[f"{s}_slope10"] = g[s].transform(
            lambda x: x.rolling(10, min_periods=2).apply(_slope, raw=True)).fillna(0.0)
    return pd.concat([df, pd.DataFrame(new)], axis=1)

