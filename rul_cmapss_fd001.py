for fname, fs in {"A: originales": FEATS_A, "B: + ventanas": FEATS_B, "C: ventanas sin colineales": FEATS_C}.items():
    for mname, m in quick_models.items():
        r = summarize(cv_eval(m, train_fe[fs], y125, groups, y_eval=y_raw, mask=mask_zone))
        rows.append({"Variables": fname, "Modelo": mname, "n_vars": len(fs), "RMSE": r["RMSE"], "MAE": r["MAE"], "R2": r["R2"]})
tbl_feats = pd.DataFrame(rows)
print(tbl_feats.round(3).to_string(index=False))

best_feat_name = (tbl_feats[tbl_feats["Modelo"] == "RandomForest"].sort_values("RMSE").iloc[0]["Variables"])
